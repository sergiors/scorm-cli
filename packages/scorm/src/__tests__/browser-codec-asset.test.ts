import { execFile } from 'node:child_process'
import { readFile, rename } from 'node:fs/promises'
import path from 'node:path'
import vm from 'node:vm'
import { fileURLToPath } from 'node:url'
import { promisify } from 'node:util'
import { beforeAll, describe, expect, it } from 'vitest'
import type { ContentPackage, PlayerState } from '@scorm-cli/core'
import type { ScoIndex } from '../sco-index'
import { createScoIndex } from '../sco-index'
import { decodeSuspendData, encodeSuspendData } from '../state-codec'

const execFileAsync = promisify(execFile)

const packageRoot = fileURLToPath(new URL('../../', import.meta.url))
/** The asset the built package reads instead of bundling at runtime. */
const codecAssetPath = path.join(packageRoot, 'dist', 'browser-codec.js')
const tsupBinary = path.join(packageRoot, 'node_modules', '.bin', 'tsup')

const content: ContentPackage = {
  metadata: { title: 'Asset parity' },
  presentation: {
    type: 'scroll',
    pages: [
      {
        type: 'page',
        id: 'page:one',
        source: 'one.mdx',
        metadata: { title: 'One' },
        content: [
          {
            type: 'questionnaire',
            id: 'quiz-one',
            contributesToScore: true,
            revealCorrectAnswers: true,
            maxAttempts: 1,
            shuffleOptions: false,
            questions: [
              {
                type: 'question',
                id: 'q-one',
                questionType: 'single-choice',
                prompt: 'Pick one',
                options: [
                  { value: 'alpha', correct: false, content: 'Alpha' },
                  { value: 'beta', correct: true, content: 'Beta' }
                ]
              }
            ]
          }
        ]
      }
    ]
  }
}

const scoIndex: ScoIndex = createScoIndex(content)

const SAVED_STATE: PlayerState = {
  location: 'page:one',
  pages: {
    'page:one': { visited: true, completed: true, answers: { 'q-one': 'beta' } }
  }
}

const RESTORED: PlayerState = {
  pages: {
    'page:one': { visited: true, completed: true, answers: { 'q-one': 'beta' } }
  }
}

/** A window whose LMS dictionary records everything the runtime writes. */
function createLmsWindow(): { window: any; values: Record<string, string> } {
  const values: Record<string, string> = {}
  const window: any = {
    __SCORM_DEVTOOLS__: false,
    parent: null,
    API: {
      LMSInitialize: () => 'true',
      LMSGetValue: (key: string) => values[key] ?? '',
      LMSSetValue: (key: string, value: string) => {
        values[key] = value
        return 'true'
      },
      LMSCommit: () => 'true',
      LMSFinish: () => 'true'
    },
    addEventListener: () => undefined,
    dispatchEvent: () => undefined,
    CustomEvent: class {}
  }
  window.parent = window
  return { window, values }
}

let built: typeof import('../../dist/index.js')

beforeAll(async () => {
  // Run the real package build so the asset under test is always generated by
  // the shipped tsup configuration, from the current codec source graph.
  try {
    await execFileAsync(tsupBinary, [], { cwd: packageRoot, timeout: 120_000 })
  } catch (error) {
    const execError = error as { stderr?: string; message: string }
    throw new Error(`scorm package build failed: ${execError.stderr ?? execError.message}`, {
      cause: error
    })
  }
  built = await import('../../dist/index.js')
}, 120_000)

describe('built browser codec asset', () => {
  it('exposes a standalone codec bundle that the packaged runtime embeds verbatim', async () => {
    const asset = await readFile(codecAssetPath, 'utf8')
    expect(asset).toContain('__scormCodec')

    // The asset evaluates on its own: no module scope, no Node builtins, and
    // the exported codec matches the source codec it was built from.
    const context: Record<string, any> = {}
    vm.runInNewContext(asset, context)
    const codec = context.__scormCodec
    expect(typeof codec.compactEncode).toBe('function')
    expect(typeof codec.compactDecode).toBe('function')

    const encoded = encodeSuspendData(scoIndex, RESTORED, 100)
    expect(JSON.parse(codec.compactEncode(scoIndex, RESTORED, 100))).toEqual(encoded)
    expect(codec.compactDecode(scoIndex, JSON.stringify(encoded))).toEqual(RESTORED)

    // The runtime the package ships embeds exactly those asset bytes.
    expect(built.createScormRuntime(scoIndex)).toContain(asset)
  })

  it('round-trips learner state through the packaged runtime with parity to the source codec', () => {
    const { window, values } = createLmsWindow()
    vm.runInNewContext(built.createScormRuntime(scoIndex), { window })

    expect(window.scormBridge.saveState(SAVED_STATE)).toBe(true)
    expect(values['cmi.core.lesson_location']).toBe('page:one')

    // What the built runtime persisted is what the source codec produces and
    // decodes back to, so the shipped asset cannot drift from the Node codec.
    const suspendData = values['cmi.suspend_data']
    expect(JSON.parse(suspendData)).toEqual(encodeSuspendData(scoIndex, RESTORED, 100))
    expect(decodeSuspendData(scoIndex, suspendData)).toEqual(RESTORED)
    expect(window.scormBridge.getResumeState()).toEqual({ location: 'page:one', ...RESTORED })
  })

  it('fails loudly when the built package cannot find its codec asset', async () => {
    // A built package must never silently fall back to bundling at runtime:
    // without the generated asset it fails with an explicit error instead.
    await rename(codecAssetPath, `${codecAssetPath}.missing`)
    try {
      expect(() => built.createScormRuntime(scoIndex)).toThrow(
        'Unable to locate generated browser codec asset'
      )
    } finally {
      await rename(`${codecAssetPath}.missing`, codecAssetPath)
    }
  })
})
